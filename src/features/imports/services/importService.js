
import { supabase } from "../../../lib/supabase/client";

async function getCurrentBusinessId() {
  const { data: authData, error: authError } =
    await supabase.auth.getUser();

  if (authError) throw authError;

  const user = authData?.user;

  if (!user) {
    throw new Error("Please log in before importing records.");
  }

  const { data: business, error } = await supabase
    .from("businesses")
    .select("id")
    .eq("owner_id", user.id)
    .maybeSingle();

  if (error) throw error;

  if (!business?.id) {
    throw new Error(
      "No business is linked to your account. Please check your business setup."
    );
  }

  return business.id;
}

async function getImportCustomers() {
  const businessId = await getCurrentBusinessId();

  const { data, error } = await supabase
    .from("customers")
    .select("id, business_id, code, name, phone, jar_rate, status, archived")
    .eq("business_id", businessId)
    .eq("archived", false)
    .order("name", { ascending: true });

  if (error) throw error;

  return data || [];
}

async function importDeliveryRows(records) {
  if (!Array.isArray(records) || records.length === 0) {
    throw new Error("There are no valid delivery rows to import.");
  }

  const businessId = await getCurrentBusinessId();

  const payload = records.map((record, index) => {
    if (!record.customerId) {
      throw new Error(`Row ${index + 1}: customer is required.`);
    }

    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(record.deliveryDate || "")
    ) {
      throw new Error(`Row ${index + 1}: delivery date is invalid.`);
    }

    if (
      !Number.isSafeInteger(record.jarQuantity) ||
      record.jarQuantity <= 0
    ) {
      throw new Error(
        `Row ${index + 1}: jar quantity must be a positive whole number.`
      );
    }

    const rate =
      record.jarRate !== null &&
      record.jarRate !== undefined &&
      record.jarRate !== ""
        ? Number(record.jarRate)
        : Number(record.customerJarRate);

    if (!Number.isFinite(rate) || rate < 0) {
      throw new Error(`Row ${index + 1}: a valid jar rate is required.`);
    }

    // Do not send "amount" when it is generated by the database.
    return {
      business_id: businessId,
      customer_id: record.customerId,
      delivery_date: record.deliveryDate,
      jar_quantity: record.jarQuantity,
      jar_rate: rate,
      notes: record.notes || "Imported from CSV/Excel",
    };
  });

  const { data, error } = await supabase
    .from("deliveries")
    .insert(payload)
    .select(
      "id, business_id, customer_id, delivery_date, jar_quantity, jar_rate, amount"
    );

  if (error) {
    if (error.code === "23505") {
      throw new Error(
        "A duplicate record may already exist. Check existing deliveries before retrying."
      );
    }

    throw error;
  }

  return {
    importedCount: data?.length ?? payload.length,
    rows: data || [],
  };
}

export const importService = {
  getImportCustomers,
  importDeliveryRows,
};

export { getImportCustomers, importDeliveryRows };
